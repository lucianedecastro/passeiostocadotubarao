(function(){
  var LANGS=["pt","en","es","fr","zh"];
  var LABELS={pt:"PT",en:"EN",es:"ES",fr:"FR",zh:"中文"};
  var HTMLLANG={pt:"pt-BR",en:"en",es:"es",fr:"fr",zh:"zh-Hans"};
  var WA="5512996450379";
  function t(l,k){ return (TT_DICT[l]&&TT_DICT[l][k]!=null)?TT_DICT[l][k]:(TT_DICT.pt[k]!=null?TT_DICT.pt[k]:""); }
  function savedLang(){
    // Site brasileiro: abre sempre em PT, salvo escolha anterior do visitante.
    try{ var s=localStorage.getItem("ttlang"); if(s&&LANGS.indexOf(s)>=0) return s; }catch(e){}
    return "pt";
  }
  function applyLang(l){
    document.documentElement.lang=HTMLLANG[l]||l;
    document.querySelectorAll("[data-i18n]").forEach(function(el){
      var k=el.getAttribute("data-i18n"); var v=t(l,k); if(v==null) return;
      var attr=el.getAttribute("data-i18n-attr");
      if(attr){ el.setAttribute(attr,v); }
      else if(el.hasAttribute("data-i18n-html")){ el.innerHTML=v; }
      else { el.textContent=v; }
    });
    document.querySelectorAll("[data-i18n-wa]").forEach(function(el){
      var msg=t(l,el.getAttribute("data-i18n-wa"));
      el.setAttribute("href","https://wa.me/"+WA+"?text="+encodeURIComponent(msg));
    });
    try{ localStorage.setItem("ttlang",l); }catch(e){}
    document.querySelectorAll("[data-ttlang]").forEach(function(b){
      b.setAttribute("aria-pressed", b.getAttribute("data-ttlang")===l ? "true":"false");
    });
    document.dispatchEvent(new CustomEvent("tt:langchanged",{detail:{lang:l}}));
  }
  window.TTi18n={ apply:applyLang, t:t, current:savedLang };

  /* ---------- acessibilidade ---------- */
  var STEPS=[90,100,112,125,140];
  function savedFont(){ try{ return parseInt(localStorage.getItem("ttfont"))||100; }catch(e){ return 100; } }
  function applyFont(p){ document.documentElement.style.fontSize=p+"%"; try{ localStorage.setItem("ttfont",p);}catch(e){} }
  function stepFont(dir){
    var cur=savedFont(); var i=STEPS.indexOf(cur); if(i<0) i=1;
    i=Math.min(STEPS.length-1,Math.max(0,i+dir)); applyFont(STEPS[i]);
  }
  function savedHC(){ try{ return localStorage.getItem("tthc")==="1"; }catch(e){ return false; } }
  function applyHC(on){ document.documentElement.classList.toggle("tt-hc",on); try{ localStorage.setItem("tthc",on?"1":"0");}catch(e){}
    var b=document.getElementById("tt-hc-btn"); if(b) b.setAttribute("aria-pressed",on?"true":"false"); }

  /* ---------- VLibras (tradutor de Libras oficial gov.br) ----------
     Integração oficial, sem esperteza: markup + script + Widget.
     O botão nativo do VLibras aparece sozinho, embaixo à direita
     (posicionado pela css/acessibilidade.css). */
  function iniciarVLibras(){
    if(document.querySelector("[vw]")) return;
    var wrapper=document.createElement("div");
    wrapper.setAttribute("vw",""); wrapper.className="enabled";
    wrapper.innerHTML='<div vw-access-button class="active"></div>'
      +'<div vw-plugin-wrapper><div class="vw-plugin-top-wrapper"></div></div>';
    document.body.appendChild(wrapper);
    var s=document.createElement("script");
    s.src="https://vlibras.gov.br/app/vlibras-plugin.js";
    s.onload=function(){ try{ new window.VLibras.Widget("https://vlibras.gov.br/app"); }
      catch(e){ console.error("[a11y] VLibras nao iniciou:",e); } };
    s.onerror=function(){ console.error("[a11y] VLibras indisponivel"); wrapper.remove(); };
    document.body.appendChild(s);
  }

  /* ---------- monta a barra ---------- */
  function buildBar(){
    var l=savedLang();
    var skip=document.createElement("a"); skip.className="tt-skip"; skip.href="#conteudo";
    skip.setAttribute("data-i18n","ui_skip"); skip.textContent=t(l,"ui_skip");
    document.body.insertBefore(skip,document.body.firstChild);

    var bar=document.createElement("div"); bar.className="tt-bar";
    bar.setAttribute("role","region"); bar.setAttribute("aria-label",t(l,"ui_a11y"));

    var lang=document.createElement("div"); lang.className="tt-grp"; lang.setAttribute("role","group"); lang.setAttribute("aria-label",t(l,"ui_lang"));
    var g=document.createElement("span"); g.className="tt-globe"; g.setAttribute("aria-hidden","true"); g.textContent="🌐"; lang.appendChild(g);
    LANGS.forEach(function(code){
      var b=document.createElement("button"); b.type="button"; b.textContent=LABELS[code];
      b.setAttribute("data-ttlang",code); b.setAttribute("lang",HTMLLANG[code]);
      b.setAttribute("aria-label",LABELS[code]);
      b.onclick=function(){ applyLang(code); };
      lang.appendChild(b);
    });

    var a11y=document.createElement("div"); a11y.className="tt-grp"; a11y.setAttribute("role","group"); a11y.setAttribute("aria-label",t(l,"ui_a11y"));
    function mk(txt,label,i18nkey,fn,id){
      var b=document.createElement("button"); b.type="button"; b.textContent=txt;
      b.setAttribute("aria-label",label); b.setAttribute("data-i18n",i18nkey); b.setAttribute("data-i18n-attr","aria-label");
      if(id) b.id=id; b.onclick=fn; return b;
    }
    a11y.appendChild(mk("A−",t(l,"ui_decr"),"ui_decr",function(){stepFont(-1);}));
    a11y.appendChild(mk("A+",t(l,"ui_incr"),"ui_incr",function(){stepFont(1);}));
    var hc=mk("◐",t(l,"ui_contrast"),"ui_contrast",function(){ applyHC(!document.documentElement.classList.contains("tt-hc")); },"tt-hc-btn");
    hc.setAttribute("aria-pressed","false"); a11y.appendChild(hc);

    bar.appendChild(lang); bar.appendChild(a11y);
    document.body.insertBefore(bar,document.body.firstChild);
  }

  function init(){
    buildBar(); iniciarVLibras();
    applyFont(savedFont()); applyHC(savedHC()); applyLang(savedLang());
  }
  if(document.readyState==="loading") document.addEventListener("DOMContentLoaded",init);
  else init();
})();
